"""Tools for manipulation of Python code samples.

Two main classes:
  Function – represents a function with name, args, body, optional return type
             and docstring.  Also carries profiling metadata (score, timing).
  Program  – contains a code preface (imports, globals) and a list of Functions.

These are used throughout AdaptSci to represent, parse, and modify equation
skeleton programs generated by the LLM.
"""
from __future__ import annotations

import ast
import dataclasses
import io
import logging
import tokenize
from collections.abc import Iterator, MutableSet, Sequence

logger = logging.getLogger(__name__)


# ─────────────────────────────────────────────────────────────────────────────
# Data classes
# ─────────────────────────────────────────────────────────────────────────────

@dataclasses.dataclass
class Function:
    """A parsed Python function."""

    name: str
    args: str
    body: str
    return_type: str | None = None
    docstring: str | None = None
    # profiling metadata (set by buffer / evaluator)
    score: float | None = None
    global_sample_nums: int | None = None
    sample_time: float | None = None
    evaluate_time: float | None = None

    def __str__(self) -> str:
        ret = f' -> {self.return_type}' if self.return_type else ''
        fn  = f'def {self.name}({self.args}){ret}:\n'
        if self.docstring:
            nl  = '\n' if self.body else ''
            fn += f'    """{self.docstring}"""{nl}'
        fn += self.body + '\n\n'
        return fn

    def __setattr__(self, name: str, value) -> None:  # type: ignore[override]
        if name == 'body' and value is not None:
            value = value.strip('\n')
        if name == 'docstring' and value is not None:
            if '"""' in value:
                value = value.strip().replace('"""', '')
        super().__setattr__(name, value)


@dataclasses.dataclass(frozen=True)
class Program:
    """A parsed Python program."""

    preface: str
    functions: list[Function]

    def __str__(self) -> str:
        out = f'{self.preface}\n' if self.preface else ''
        out += '\n'.join(str(f) for f in self.functions)
        return out

    def find_function_index(self, function_name: str) -> int:
        names = [f.name for f in self.functions]
        count = names.count(function_name)
        if count == 0:
            raise ValueError(f'Function {function_name!r} not found in program.')
        if count > 1:
            raise ValueError(f'Function {function_name!r} appears more than once.')
        return names.index(function_name)

    def get_function(self, function_name: str) -> Function:
        return self.functions[self.find_function_index(function_name)]


# ─────────────────────────────────────────────────────────────────────────────
# Parser
# ─────────────────────────────────────────────────────────────────────────────

class _ProgramVisitor(ast.NodeVisitor):
    def __init__(self, sourcecode: str):
        self._lines    = sourcecode.splitlines()
        self._preface  = ''
        self._functions: list[Function] = []

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        if node.col_offset == 0:
            if not self._functions:
                if node.decorator_list:
                    start = min(d.lineno for d in node.decorator_list)
                    self._preface = '\n'.join(self._lines[:start - 1])
                else:
                    self._preface = '\n'.join(self._lines[:node.lineno - 1])

            end_line       = node.end_lineno
            body_start     = node.body[0].lineno - 1
            docstring: str | None = None

            if (isinstance(node.body[0], ast.Expr)
                    and isinstance(node.body[0].value, ast.Constant)
                    and isinstance(node.body[0].value.value, str)):
                docstring = f'  """{ast.literal_eval(ast.unparse(node.body[0]))}"""'
                body_start = node.body[1].lineno - 1 if len(node.body) > 1 else end_line

            self._functions.append(Function(
                name=node.name,
                args=ast.unparse(node.args),
                return_type=ast.unparse(node.returns) if node.returns else None,
                docstring=docstring,
                body='\n'.join(self._lines[body_start:end_line]),
            ))
        self.generic_visit(node)

    def return_program(self) -> Program:
        return Program(preface=self._preface, functions=self._functions)


def text_to_program(text: str) -> Program:
    """Parse source text into a Program object."""
    try:
        tree = ast.parse(text)
        visitor = _ProgramVisitor(text)
        visitor.visit(tree)
        return visitor.return_program()
    except Exception as e:
        logger.warning('Failed to parse program: %s', e)
        raise


def text_to_function(text: str) -> Function:
    """Parse source text containing exactly one function."""
    prog = text_to_program(text)
    if len(prog.functions) != 1:
        raise ValueError(
            f'Expected 1 function, got {len(prog.functions)}.')
    return prog.functions[0]


# ─────────────────────────────────────────────────────────────────────────────
# Token-level utilities
# ─────────────────────────────────────────────────────────────────────────────

def _tokenize(code: str) -> Iterator[tokenize.TokenInfo]:
    return tokenize.tokenize(io.BytesIO(code.encode()).readline)


def _untokenize(tokens: Sequence[tokenize.TokenInfo]) -> str:
    return tokenize.untokenize(tokens).decode()


def _yield_token_and_is_call(
    code: str,
) -> Iterator[tuple[tokenize.TokenInfo, bool]]:
    try:
        prev, is_attr = None, False
        for tok in _tokenize(code):
            if (prev
                    and prev.type == tokenize.NAME
                    and tok.type == tokenize.OP
                    and tok.string == '('):
                yield prev, not is_attr
                is_attr = False
            else:
                if prev:
                    is_attr = (prev.type == tokenize.OP and prev.string == '.')
                    yield prev, False
            prev = tok
        if prev:
            yield prev, False
    except Exception as e:
        logger.warning('Tokenisation failed: %s', e)
        raise


def rename_function_calls(code: str, source_name: str, target_name: str) -> str:
    """Replace all calls to source_name with target_name."""
    if source_name not in code:
        return code
    modified = []
    for tok, is_call in _yield_token_and_is_call(code):
        if is_call and tok.string == source_name:
            modified.append(tokenize.TokenInfo(
                tok.type, target_name, tok.start, tok.end, tok.line))
        else:
            modified.append(tok)
    return _untokenize(modified)


def get_functions_called(code: str) -> MutableSet[str]:
    """Return the set of all function names called in code."""
    return {tok.string for tok, is_call in _yield_token_and_is_call(code)
            if is_call}


def yield_decorated(code: str, module: str, name: str) -> Iterator[str]:
    """Yield names of functions decorated with @module.name."""
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.FunctionDef):
            for dec in node.decorator_list:
                attr = dec if isinstance(dec, ast.Attribute) else (
                    dec.func if isinstance(dec, ast.Call) else None)
                if (attr is not None
                        and isinstance(attr.value, ast.Name)
                        and attr.value.id == module
                        and attr.attr == name):
                    yield node.name

"""
model_wrapper.py
----------------
HuggingFace-backed language model wrapper.

Batching design
---------------
ONE batch_size argument controls every model.generate() call.

  Greedy:
    Questions are chunked into groups of batch_size.
    Each chunk → one model.generate() call.

  BoN / DN-BoN  (per question):
    For each question, N samples are generated by calling
    _generate_batch_raw() in a loop of ceil(N / batch_size) calls,
    each of at most batch_size sequences.

    Examples  (N=8):
      batch_size=4  → 2 calls of 4 each
      batch_size=8  → 1 call  of 8
      batch_size=16 → 1 call  of 8  (capped at N, no wasted VRAM)

    This is the correct design: batch_size controls how many sequences
    the GPU processes in one forward pass; N controls how many samples
    you want. They are independent knobs.
"""

import logging
import math
from typing import List, Optional, Dict, Any

import torch
from tqdm import tqdm

logger = logging.getLogger(__name__)

DEFAULT_MAX_NEW_TOKENS = 1024
DEFAULT_TEMPERATURE    = 0.7
DEFAULT_TOP_P          = 0.95
DEFAULT_TOP_K          = 50

MATH_SYSTEM_PROMPT = (
    "You are a careful mathematics assistant. "
    "Solve the problem step by step and put your final answer in \\boxed{}."
)


class HFModelWrapper:
    """
    HuggingFace causal / seq2seq LM wrapper.

    Parameters
    ----------
    model_name_or_path : HF Hub model id or local path
    batch_size         : sequences per model.generate() call.
                         Used for Greedy chunking AND for BoN/DN-BoN sampling
                         (N samples generated in ceil(N/batch_size) calls).
                         Recommended: set to N for BoN so all N samples fit
                         in one call; set higher for Greedy throughput.
    """

    def __init__(
        self,
        model_name_or_path: str,
        batch_size: int = 8,
        device: str = "auto",
        dtype: str = "auto",
        load_in_8bit: bool = False,
        load_in_4bit: bool = False,
        max_new_tokens: int = DEFAULT_MAX_NEW_TOKENS,
        temperature: float = DEFAULT_TEMPERATURE,
        top_p: float = DEFAULT_TOP_P,
        top_k: int = DEFAULT_TOP_K,
        system_prompt: str = MATH_SYSTEM_PROMPT,
        trust_remote_code: bool = False,
        cache_dir: Optional[str] = None,
    ):
        from transformers import (
            AutoTokenizer, AutoModelForCausalLM,
            AutoModelForSeq2SeqLM, BitsAndBytesConfig,
        )

        self.model_name     = model_name_or_path
        self.batch_size     = batch_size
        self.max_new_tokens = max_new_tokens
        self.temperature    = temperature
        self.top_p          = top_p
        self.top_k          = top_k
        self.system_prompt  = system_prompt

        # dtype
        if dtype == "auto":
            torch_dtype = torch.float16 if torch.cuda.is_available() else torch.float32
        else:
            torch_dtype = getattr(torch, dtype)

        # quantisation
        bnb_cfg = None
        if load_in_4bit:
            bnb_cfg = BitsAndBytesConfig(
                load_in_4bit=True, bnb_4bit_compute_dtype=torch.float16,
                bnb_4bit_use_double_quant=True, bnb_4bit_quant_type="nf4",
            )
        elif load_in_8bit:
            bnb_cfg = BitsAndBytesConfig(load_in_8bit=True)

        common_kw: Dict[str, Any] = dict(
            pretrained_model_name_or_path=model_name_or_path,
            trust_remote_code=trust_remote_code,
        )
        if cache_dir:
            common_kw["cache_dir"] = cache_dir
        if bnb_cfg:
            common_kw["quantization_config"] = bnb_cfg
            common_kw["device_map"] = "auto"
        elif device == "auto":
            common_kw["device_map"] = "auto"
            common_kw["dtype"] = torch_dtype
        else:
            common_kw["dtype"] = torch_dtype

        logger.info(f"Loading tokenizer for {model_name_or_path} ...")
        self.tokenizer = AutoTokenizer.from_pretrained(
            model_name_or_path, trust_remote_code=trust_remote_code,
            cache_dir=cache_dir,
        )
        self.tokenizer.padding_side = "left"
        if self.tokenizer.pad_token_id is None:
            self.tokenizer.pad_token_id = self.tokenizer.eos_token_id

        logger.info(f"Loading model {model_name_or_path} ...")
        try:
            self.model = AutoModelForCausalLM.from_pretrained(**common_kw)
            self._is_seq2seq = False
        except Exception:
            self.model = AutoModelForSeq2SeqLM.from_pretrained(**common_kw)
            self._is_seq2seq = True
            self.tokenizer.padding_side = "right"

        if device not in ("auto",) and not bnb_cfg:
            self.model = self.model.to(device)
        self.device = next(self.model.parameters()).device
        self.model.eval()
        logger.info(f"Model loaded on {self.device}  |  batch_size={self.batch_size}")

    # ── prompt building ───────────────────────────────────────────────────────

    def _build_prompt(self, question: str) -> str:
        if getattr(self.tokenizer, "chat_template", None):
            messages: List[Dict[str, str]] = []
            if self.system_prompt:
                messages.append({"role": "system", "content": self.system_prompt})
            messages.append({"role": "user", "content": question})
            return self.tokenizer.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True
            )
        if self.system_prompt:
            return f"{self.system_prompt}\n\nProblem: {question}\nSolution:"
        return f"Problem: {question}\nSolution:"

    # ── core generation  (ONLY place model.generate() is called) ─────────────

    @torch.no_grad()
    def _generate_batch_raw(
        self,
        prompts: List[str],
        do_sample: bool = False,
        temperature: Optional[float] = None,
        top_p: Optional[float] = None,
        top_k: Optional[int] = None,
        max_new_tokens: Optional[int] = None,
    ) -> List[str]:
        """
        Tokenise `prompts` into one left-padded batch and call model.generate()
        exactly once.  Returns decoded strings with prompt stripped.
        """
        mnt = max_new_tokens or self.max_new_tokens
        enc = self.tokenizer(
            prompts, return_tensors="pt", padding=True,
            truncation=True, max_length=2048,
        ).to(self.device)
        prompt_len = enc["input_ids"].shape[1]

        gen_kwargs: Dict[str, Any] = dict(
            max_new_tokens=mnt, do_sample=do_sample,
            pad_token_id=self.tokenizer.pad_token_id,
            eos_token_id=self.tokenizer.eos_token_id,
        )
        if do_sample:
            gen_kwargs["temperature"] = temperature or self.temperature
            gen_kwargs["top_p"]       = top_p       or self.top_p
            gen_kwargs["top_k"]       = top_k       or self.top_k

        output_ids = self.model.generate(**enc, **gen_kwargs)
        if not self._is_seq2seq:
            output_ids = output_ids[:, prompt_len:]
        return [
            self.tokenizer.decode(ids, skip_special_tokens=True).strip()
            for ids in output_ids
        ]

    # ── public API ────────────────────────────────────────────────────────────

    def generate_greedy_batch(
        self,
        questions: List[str],
        max_new_tokens: Optional[int] = None,
    ) -> List[str]:
        """
        Greedy-decode a list of questions in chunks of batch_size.
        Each chunk → one model.generate() call.
        """
        prompts  = [self._build_prompt(q) for q in questions]
        bs       = self.batch_size
        n_chunks = math.ceil(len(prompts) / bs)
        results: List[str] = []

        chunk_bar = tqdm(
            range(0, len(prompts), bs), total=n_chunks,
            desc=f"[Greedy] generate (bs={bs})", unit="chunk",
            dynamic_ncols=True, colour="green",
        )
        for start in chunk_bar:
            chunk = prompts[start : start + bs]
            chunk_bar.set_postfix(
                q=f"{min(start+bs, len(prompts))}/{len(prompts)}", refresh=False
            )
            results.extend(
                self._generate_batch_raw(chunk, do_sample=False,
                                         max_new_tokens=max_new_tokens)
            )
        chunk_bar.close()
        return results

    def generate_samples(
        self,
        question: str,
        N: int = 8,
        temperature: Optional[float] = None,
        top_p: Optional[float] = None,
        top_k: Optional[int] = None,
        max_new_tokens: Optional[int] = None,
    ) -> List[str]:
        """
        Generate N samples for ONE question.
        Loops ceil(N / batch_size) calls, each of min(remaining, batch_size).
        """
        prompt    = self._build_prompt(question)
        samples: List[str] = []
        remaining = N

        while remaining > 0:
            this_bs = min(remaining, self.batch_size)
            decoded = self._generate_batch_raw(
                [prompt] * this_bs,
                do_sample=True,
                temperature=temperature,
                top_p=top_p,
                top_k=top_k,
                max_new_tokens=max_new_tokens,
            )
            samples.extend(decoded)
            remaining -= this_bs

        return samples   # length == N

    def generate_samples_flat(
        self,
        questions: List[str],
        N: int = 8,
        temperature: Optional[float] = None,
        top_p: Optional[float] = None,
        top_k: Optional[int] = None,
        max_new_tokens: Optional[int] = None,
    ) -> List[List[str]]:
        """
        Generate N samples for EVERY question in one flat batched pass.

        Strategy
        --------
        Build a flat list of Q*N prompts:
          [prompt(q0)]*N + [prompt(q1)]*N + ... + [prompt(q_{Q-1})]*N

        Chunk it into groups of batch_size and call _generate_batch_raw()
        once per chunk.  Each chunk is one model.generate() call.

        With Q=466, N=8, batch_size=128:
          flat list  = 466 × 8 = 3728 prompts
          chunks     = ceil(3728 / 128) = 30 generate() calls
          vs old way = 466 generate() calls of 8 each

        Returns List[List[str]] shape [Q, N].
        """
        import math as _math

        # Build flat prompt list: Q*N prompts
        prompts_flat: List[str] = []
        for q in questions:
            p = self._build_prompt(q)
            prompts_flat.extend([p] * N)

        total    = len(prompts_flat)   # Q * N
        bs       = self.batch_size
        n_chunks = _math.ceil(total / bs)
        decoded_flat: List[str] = []

        chunk_bar = tqdm(
            range(0, total, bs),
            total=n_chunks,
            desc=f"[generate] flat batch  bs={bs}  Q={len(questions)}  N={N}",
            unit="chunk",
            dynamic_ncols=True,
            colour="blue",
            leave=True,
        )
        for start in chunk_bar:
            chunk = prompts_flat[start : start + bs]
            q_done = min((start + bs) // N, len(questions))
            chunk_bar.set_postfix(
                q=f"{q_done}/{len(questions)}",
                seqs=f"{min(start+bs, total)}/{total}",
                refresh=False,
            )
            decoded_flat.extend(
                self._generate_batch_raw(
                    chunk,
                    do_sample=True,
                    temperature=temperature,
                    top_p=top_p,
                    top_k=top_k,
                    max_new_tokens=max_new_tokens,
                )
            )
        chunk_bar.close()

        # Reshape [Q*N] → [[N], [N], ..., [N]]
        return [decoded_flat[i * N : (i + 1) * N] for i in range(len(questions))]

    # ── convenience single-question greedy ───────────────────────────────────

    def generate_greedy(
        self,
        question: str,
        max_new_tokens: Optional[int] = None,
    ) -> str:
        return self.generate_greedy_batch(
            [question], max_new_tokens=max_new_tokens
        )[0]